using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using AutismVR.Comfort;
using Unity.Pipeline.Commands;
using UnityEngine;

namespace AutismVR.Editor
{
    // Runs one scripted session against each child's profile and writes the comfort timeline, so the
    // difference between the three personalities can be read without a headset.
    public static class ComfortScenarioCommands
    {
        public const string OutputPath = "docs/verification/f4-comfort-trigger-engine/scenario.md";

        const float Step = 0.1f;
        const float ShoutSeconds = 10f;
        const float MaxCalmSeconds = 300f;

        [CliCommand("autismvr_comfort_scenario", "Run the shout-then-calm scenario for each child and write the timeline")]
        public static string WriteScenario()
        {
            var catalog = TriggerCatalog.LoadDefault();
            var text = new StringBuilder();
            text.AppendLine("# F4 comfort scenario");
            text.AppendLine();
            text.AppendLine("Generated by `autismvr_comfort_scenario` from the built-in trigger catalog and each child's");
            text.AppendLine("provisional profile. Two sessions: a single shout, then a hostile one.");
            text.AppendLine("Mic loudness is scripted here; in the headset it arrives with the voice feature (F6).");

            AppendOneShout(text, catalog);
            foreach (var id in CharacterProfileCommands.ProfileIds)
                AppendProfile(text, CharacterProfileCommands.Load(id), catalog);

            var path = Path.Combine(Directory.GetParent(Application.dataPath).FullName, OutputPath);
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, text.ToString());
            return OutputPath;
        }

        // A milder session where the personalities show: one shout from 1.2 m, then 60 s of quiet at 1.2 m.
        static void AppendOneShout(StringBuilder text, TriggerCatalog catalog)
        {
            text.AppendLine();
            text.AppendLine("## One shout from 1.2 m, then quiet at 1.2 m for 60 s");
            text.AppendLine();
            text.AppendLine("| child | start | after the shout | reaction after the shout | after 60 s quiet | reaction |");
            text.AppendLine("|---|---|---|---|---|---|");
            foreach (var id in CharacterProfileCommands.ProfileIds)
            {
                var profile = CharacterProfileCommands.Load(id);
                var engine = new ComfortEngine(profile, catalog);
                var shout = Frame(1.2f, false, -5f);
                while (engine.Log.Events.Count == 0)
                    engine.Step(shout, Step);
                engine.Step(Frame(1.2f, false, -50f), Step);
                var afterShout = engine.Model.Comfort;
                var reactionAfterShout = engine.Reactions.Current;
                for (var t = 0f; t < 60f; t += Step)
                    engine.Step(Frame(1.2f, false, -50f), Step);
                text.AppendLine($"| {profile.DisplayName} | {profile.StartingComfort:0.00} | {afterShout:0.00} | {reactionAfterShout} | {engine.Model.Comfort:0.00} | {engine.Reactions.Current} |");
            }
        }

        static void AppendProfile(StringBuilder text, Characters.CharacterProfile profile, TriggerCatalog catalog)
        {
            var engine = new ComfortEngine(profile, catalog);
            text.AppendLine();
            text.AppendLine($"## {profile.DisplayName} (`{profile.Id}`): shouting and staring at 0.5 m for {ShoutSeconds:0} s, then quiet at 2 m");
            text.AppendLine();
            text.AppendLine($"Start {profile.StartingComfort:0.00}, greets at {profile.GreetingThreshold:0.00}, recovers {profile.RecoveryPerSecond:0.000}/s in a meltdown.");
            text.AppendLine();
            text.AppendLine("| t (s) | phase | comfort | reaction | hits this second |");
            text.AppendLine("|---|---|---|---|---|");

            var shouting = Frame(0.5f, true, -5f);
            var calm = Frame(2f, false, -50f);
            var logged = 0;
            var ticks = 0;
            while (!engine.Log.Greeted && engine.Time < ShoutSeconds + MaxCalmSeconds)
            {
                var shoutPhase = engine.Time < ShoutSeconds - 1e-4f;
                engine.Step(shoutPhase ? shouting : calm, Step);
                if (++ticks % 10 != 0 && !engine.Log.Greeted)
                    continue;

                var hits = engine.Log.Events.Skip(logged).Select(e => e.TriggerId).ToList();
                logged = engine.Log.Events.Count;
                text.AppendLine($"| {engine.Time:0} | {(shoutPhase ? "shouting close" : "quiet, 2 m")} | {engine.Model.Comfort:0.00} | {engine.Reactions.Current} | {Summarise(hits)} |");
            }

            var counts = engine.Log.TriggerCounts(catalog);
            text.AppendLine();
            text.AppendLine($"Outcome: greeted {Yes(engine.Log.Greeted)} at {engine.Time:0} s; meltdown {Yes(engine.Log.MeltdownHappened)}; de-escalated {Yes(engine.Log.Deescalated)}.");
            text.AppendLine($"Triggers hit: {(counts.Count == 0 ? "none" : string.Join(", ", counts.Select(pair => $"{pair.Key} ×{pair.Value}")))}.");
        }

        static string Summarise(List<string> hits) =>
            hits.Count == 0 ? "" : string.Join(", ", hits.GroupBy(id => id).Select(group => group.Count() > 1 ? $"{group.Key} ×{group.Count()}" : group.Key));

        static string Yes(bool value) => value ? "yes" : "no";

        static SensorFrame Frame(float distance, bool lookingAtChild, float dbfs)
        {
            var childHead = new Vector3(0f, 1.1f, 0f);
            var head = new Vector3(0f, 1.6f, distance);
            return new SensorFrame
            {
                HeadPosition = head,
                HeadForward = lookingAtChild ? (childHead - head).normalized : Vector3.right,
                Hands = new List<Vector3> { head + new Vector3(-0.25f, -0.7f, 0f), head + new Vector3(0.25f, -0.7f, 0f) },
                ChildHead = childHead,
                ChildChest = new Vector3(0f, 0.9f, 0f),
                ChildPosition = Vector3.zero,
                LoudnessDbfs = dbfs,
            };
        }
    }
}
